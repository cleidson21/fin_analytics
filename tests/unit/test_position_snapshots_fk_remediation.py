def test_structural_schema_validation_post_migration(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
):
    """
    Verifies that SQLite PRAGMA inspection matches the exact post-remediation contract:
    - Invalid FK to accounts is absent.
    - Valid FK to assets(id) is present.
    - Unique constraint uq_position_snapshot_account_asset_date is preserved.
    - Primary key and all 12 columns are preserved.
    - All 4 indexes are preserved.
    - No temporary or orphan tables remain.
    """
    db_path = tmp_path / "structural_validation.db"
    assert "fin_analytics.db" not in db_path.name

    with sqlite3.connect(db_path) as conn:
        _create_position_snapshot_fixture(conn)
        conn.commit()

    config = _safe_alembic_config(db_path, monkeypatch)
    _upgrade_with_foreign_keys(config, REMEDIATION_REVISION)

    with sqlite3.connect(db_path) as conn:
        cursor = conn.cursor()

        # 1. Foreign keys list
        cursor.execute("PRAGMA foreign_key_list(position_snapshots);")
        fks = cursor.fetchall()
        # Format: (id, seq, table, from, to, on_update, on_delete, match)
        assert len(fks) == 1, f"Expected exactly 1 FK, found: {fks}"
        fk_table = fks[0][2]
        fk_from = fks[0][3]
        fk_to = fks[0][4]
        assert fk_table == "assets", f"FK target must be 'assets', got {fk_table}"
        assert fk_from == "asset_id", f"FK source must be 'asset_id', got {fk_from}"
        assert fk_to == "id", f"FK target column must be 'id', got {fk_to}"

        # 2. Columns (PRAGMA table_xinfo)
        cursor.execute("PRAGMA table_xinfo(position_snapshots);")
        cols = {
            row[1]: {
                "type": row[2],
                "notnull": row[3],
                "default": row[4],
                "pk": row[5],
            }
            for row in cursor.fetchall()
        }
        expected_columns = {
            "id": {"type": "VARCHAR(36)", "notnull": 1, "pk": 1},
            "account_id": {"type": "VARCHAR(36)", "notnull": 1, "pk": 0},
            "asset_id": {"type": "VARCHAR(36)", "notnull": 1, "pk": 0},
            "reference_date": {"type": "VARCHAR(10)", "notnull": 1, "pk": 0},
            "quantity": {"type": "NUMERIC(18, 8)", "notnull": 1, "pk": 0},
            "avg_price": {"type": "NUMERIC(18, 6)", "notnull": 0, "pk": 0},
            "source_type": {"type": "VARCHAR", "notnull": 1, "pk": 0},
            "run_id": {"type": "VARCHAR(36)", "notnull": 0, "pk": 0},
            "is_manual": {"type": "INTEGER", "notnull": 1, "pk": 0},
            "created_at": {"type": "DATETIME", "notnull": 1, "pk": 0},
            "updated_at": {"type": "DATETIME", "notnull": 1, "pk": 0},
            "current_value": {"type": "NUMERIC(18, 2)", "notnull": 0, "pk": 0},
        }
        assert set(cols) == set(expected_columns)
        for col_name, expected_meta in expected_columns.items():
            assert cols[col_name]["type"] == expected_meta["type"]
            assert cols[col_name]["notnull"] == expected_meta["notnull"]
            assert cols[col_name]["pk"] == expected_meta["pk"]
            assert cols[col_name]["default"] is None

        # 3. Indexes (PRAGMA index_list)
        cursor.execute("PRAGMA index_list(position_snapshots);")
        indexes = cursor.fetchall()
        index_names = {idx[1] for idx in indexes}
        expected_indexes = {
            "ix_position_snapshots_account_id",
            "ix_position_snapshots_asset_id",
            "ix_position_snapshots_reference_date",
            "ix_position_snapshots_run_id",
        }
        assert expected_indexes.issubset(index_names), f"Missing indexes: {expected_indexes - index_names}"

        # Check unique constraint index exists
        unique_indexes = [idx for idx in indexes if idx[2] == 1]  # unique == 1
        assert len(unique_indexes) >= 1
        # Check columns of unique constraint
        cursor.execute(f"PRAGMA index_info('{unique_indexes[0][1]}');")
        unique_cols = [row[2] for row in cursor.fetchall()]
        assert set(unique_cols) == {"account_id", "asset_id", "reference_date"}

        # 4. No temporary tables
        cursor.execute("SELECT name FROM sqlite_master WHERE type='table';")
        tables = [row[0] for row in cursor.fetchall()]
        assert not any("tmp" in t.lower() or "alembic_tmp" in t.lower() for t in tables)

        cursor.execute("PRAGMA foreign_key_check('position_snapshots');")
        assert cursor.fetchall() == []


