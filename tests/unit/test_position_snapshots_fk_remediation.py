def test_migration_is_noop_for_canonical_schema(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
):
    """Stamp forward without rebuilding an already-correct canonical table."""
    db_path = tmp_path / "canonical_noop.db"
    assert "fin_analytics.db" not in db_path.name

    with sqlite3.connect(db_path) as conn:
        _create_position_snapshot_fixture(conn, invalid_account_foreign_key=False)
        conn.execute(
            """
            CREATE TRIGGER preserve_on_canonical_schema
            AFTER UPDATE ON position_snapshots
            BEGIN
                SELECT 1;
            END;
            """
        )
        conn.commit()

    config = _safe_alembic_config(db_path, monkeypatch)
    _upgrade_with_foreign_keys(config, REMEDIATION_REVISION)

    with sqlite3.connect(db_path) as conn:
        rev = conn.execute("SELECT version_num FROM alembic_version;").fetchone()[0]
        assert rev == REMEDIATION_REVISION
        trigger = conn.execute(
            "SELECT name FROM sqlite_master WHERE type='trigger' AND name=?;",
            ("preserve_on_canonical_schema",),
        ).fetchone()
        assert trigger == ("preserve_on_canonical_schema",)
        fks = conn.execute(
            "PRAGMA foreign_key_list(position_snapshots);"
        ).fetchall()
        assert len(fks) == 1
        assert fks[0][2:5] == ("assets", "asset_id", "id")


