        assert conn.execute(
            "SELECT version_num FROM alembic_version"
        ).fetchone()[0] == PRE_REMEDIATION_HEAD
        assert conn.execute(
            "SELECT sql FROM sqlite_master WHERE type='table' AND name='position_snapshots'"
        ).fetchone()[0] == original_table_sql
        assert conn.execute(
            "SELECT id FROM position_snapshots"
        ).fetchall() == [(snapshot_id,)]
        assert conn.execute(
            "SELECT account_id, asset_id, reference_date FROM snapshot_annotations"
        ).fetchall() == [("account-001", asset_id, "2026-10-14")]
        assert conn.execute(
            "SELECT name FROM sqlite_master WHERE name='_alembic_tmp_position_snapshots'"
        ).fetchone() is None


