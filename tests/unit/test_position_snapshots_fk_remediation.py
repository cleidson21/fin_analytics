def test_migration_preserves_223_synthetic_snapshots(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
):
    """
    Verifies that Alembic migration b7e2d1a4c9f3 correctly drops the invalid FK
    while preserving 223 synthetic snapshots with 100% fidelity:
    - Same IDs
    - Same business keys (account_id, asset_id, reference_date)
    - Same Decimal precisions (8-decimal quantity, 6-decimal avg_price, 2-decimal current_value)
    - Same manual flags (0 and 1)
    - Same run_id provenance and timestamps
    - Matching deterministic SHA256 digest before and after
    - Zero duplicates, zero data loss
    """
    db_path = tmp_path / "preserve_223_snapshots.db"
    assert "fin_analytics.db" not in db_path.name

    with sqlite3.connect(db_path) as conn:
        _create_position_snapshot_fixture(conn)

        # Create 25 synthetic assets
        asset_ids = [str(uuid.uuid4()) for _ in range(25)]
        for i, aid in enumerate(asset_ids):
            conn.execute(
                """
                INSERT INTO assets (id, ticker, asset_class, currency, source, is_active, created_at, updated_at)
                VALUES (?, ?, 'STOCK', 'BRL', 'MYPROFIT_IMPORT', 1, '2026-10-01 10:00:00', '2026-10-01 10:00:00')
                """,
                (aid, f"TICKER{i:02d}"),
            )

        # Generate exactly 223 synthetic snapshots across various realistic scenarios
        accounts = ["acc-alpha", "acc-beta", "acc-gamma"]
        dates = [
            "2026-09-30", "2026-10-01", "2026-10-02", "2026-10-03",
            "2026-10-04", "2026-10-05", "2026-10-10", "2026-10-13",
        ]
        synthetic_rows: List[tuple] = []

        count = 0
        for date in dates:
            for acc in accounts:
                for a_idx, aid in enumerate(asset_ids):
                    if count >= 223:
                        break
                    snap_id = str(uuid.uuid4())
                    # Quantity with various decimal precisions
                    if a_idx == 0:
                        qty = Decimal("0.00140000")  # BTC-like
                    elif a_idx == 1:
                        qty = Decimal("0.24000000")  # Tesouro-like
                    else:
                        qty = Decimal(f"{(count + 1) * 10}.00000000")

                    # avg_price (6 decimals) or None
                    avg_p = Decimal(f"{40 + (count % 15)}.123456") if count % 7 != 0 else None

                    # current_value (2 decimals) or None
                    cur_v = Decimal(f"{1000 + (count * 25)}.50") if count % 3 != 0 else None

                    is_manual = 1 if (count % 11 == 0) else 0
                    run_id = str(uuid.uuid4()) if (count % 5 != 0) else None
                    created_at = f"2026-10-01 10:{count % 60:02d}:00"
                    updated_at = f"2026-10-02 11:{count % 60:02d}:00"
                    source_type = "MYPROFIT_ATIVOS" if is_manual == 0 else "MANUAL"

                    row = (
                        snap_id,
                        acc,
                        aid,
                        date,
                        str(qty),
                        str(avg_p) if avg_p is not None else None,
                        source_type,
                        run_id,
                        is_manual,
                        created_at,
                        updated_at,
                        str(cur_v) if cur_v is not None else None,
                    )
                    synthetic_rows.append(row)
                    count += 1
                if count >= 223:
                    break
            if count >= 223:
                break

        assert len(synthetic_rows) == 223

        conn.executemany(
            """
            INSERT INTO position_snapshots (
                id, account_id, asset_id, reference_date, quantity, avg_price,
                source_type, run_id, is_manual, created_at, updated_at, current_value
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            synthetic_rows,
        )
        conn.commit()

        # Compute deterministic pre-migration hash and canonical records
        cursor = conn.cursor()
        cursor.execute(
            """
            SELECT id, account_id, asset_id, reference_date, quantity, avg_price,
                   source_type, run_id, is_manual, created_at, updated_at, current_value
            FROM position_snapshots
            ORDER BY id
            """
        )
        pre_records = cursor.fetchall()
        assert len(pre_records) == 223
        pre_hash = hashlib.sha256(json.dumps(pre_records, sort_keys=True).encode()).hexdigest()

    # Apply the Alembic migration
    config = _safe_alembic_config(db_path, monkeypatch)
    _upgrade_with_foreign_keys(config, REMEDIATION_REVISION)

    # Validate post-migration data integrity
    with sqlite3.connect(db_path) as conn:
        cursor = conn.cursor()
        cursor.execute(
            """
            SELECT id, account_id, asset_id, reference_date, quantity, avg_price,
                   source_type, run_id, is_manual, created_at, updated_at, current_value
            FROM position_snapshots
            ORDER BY id
            """
        )
        post_records = cursor.fetchall()
        assert len(post_records) == 223

        post_hash = hashlib.sha256(json.dumps(post_records, sort_keys=True).encode()).hexdigest()
        assert pre_hash == post_hash, "Deterministic snapshot payload changed during migration!"

        # Explicit per-record verification
        for pre, post in zip(pre_records, post_records):
            assert pre[0] == post[0]  # id
            assert pre[1] == post[1]  # account_id
            assert pre[2] == post[2]  # asset_id
            assert pre[3] == post[3]  # reference_date
            assert Decimal(str(pre[4])) == Decimal(str(post[4]))  # quantity
            if pre[5] is not None:
                assert Decimal(str(pre[5])) == Decimal(str(post[5]))  # avg_price
            else:
                assert post[5] is None
            assert pre[6] == post[6]  # source_type
            assert pre[7] == post[7]  # run_id
            assert pre[8] == post[8]  # is_manual
            assert pre[9] == post[9]  # created_at
            assert pre[10] == post[10]  # updated_at
            if pre[11] is not None:
                assert Decimal(str(pre[11])) == Decimal(str(post[11]))  # current_value
            else:
                assert post[11] is None


