def test_account_id_logical_reference_preserved():
    """
    Validates that:
    - PositionSnapshotModel.account_id is mandatory and indexed.
    - PositionSnapshotModel declares no physical ForeignKey for account_id.
    - PositionSnapshotModel declares only 1 physical ForeignKey (assets.id).
    - accounts table composite primary key (provider, external_id) is untouched.
    """
    table = PositionSnapshotModel.__table__
    account_col = table.columns["account_id"]
    assert account_col.nullable is False
    assert account_col.index is True
    assert len(account_col.foreign_keys) == 0

    asset_col = table.columns["asset_id"]
    assert len(asset_col.foreign_keys) == 1
    fk = next(iter(asset_col.foreign_keys))
    assert fk.target_fullname == "assets.id"

    # Only 1 FK on entire table
    assert len(table.foreign_keys) == 1


