def test_migration_refuses_inbound_foreign_key_before_rebuild(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
):
    """Reject a composite inbound FK without changing the source table or data."""
    db_path = tmp_path / "inbound_foreign_key.db"
    assert "fin_analytics.db" not in db_path.name

    snapshot_id = str(uuid.uuid4())
    asset_id = str(uuid.uuid4())
    with sqlite3.connect(db_path) as conn:
        _create_position_snapshot_fixture(conn)
        conn.execute(
            """
            INSERT INTO assets (
                id, ticker, asset_class, currency, source, is_active,
                created_at, updated_at
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                asset_id,
                "SAFE3",
                "ACAO",
                "BRL",
                "TEST",
                1,
                "2026-10-14 12:00:00",
                "2026-10-14 12:00:00",
            ),
        )
        conn.execute(
            """
            INSERT INTO position_snapshots (
                id, account_id, asset_id, reference_date, quantity, avg_price,
                source_type, run_id, is_manual, created_at, updated_at
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                snapshot_id,
                "account-001",
                asset_id,
                "2026-10-14",
                1,
                "10.00",
                "MYPROFIT_ATIVOS",
                None,
                0,
                "2026-10-14 12:00:00",
                "2026-10-14 12:00:00",
            ),
        )
        conn.executescript(
            """
            CREATE TABLE snapshot_annotations (
                id INTEGER PRIMARY KEY,
                account_id VARCHAR(36) NOT NULL,
                asset_id VARCHAR(36) NOT NULL,
                reference_date VARCHAR(10) NOT NULL,
                FOREIGN KEY (account_id, asset_id, reference_date)
                    REFERENCES position_snapshots(
                        account_id, asset_id, reference_date
                    )
            );
            """
        )
        conn.execute(
            """
            INSERT INTO snapshot_annotations (
                id, account_id, asset_id, reference_date
            ) VALUES (?, ?, ?, ?)
            """,
            (1, "account-001", asset_id, "2026-10-14"),
        )
        original_table_sql = conn.execute(
            "SELECT sql FROM sqlite_master WHERE type='table' AND name='position_snapshots'"
        ).fetchone()[0]
        conn.commit()

    config = _safe_alembic_config(db_path, monkeypatch)
    with pytest.raises(RuntimeError, match="inbound foreign keys"):
        _upgrade_with_foreign_keys(config, REMEDIATION_REVISION)

