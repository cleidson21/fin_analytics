        with pytest.raises(sqlite3.OperationalError) as exc_info:
            cursor.execute(
                """
                INSERT INTO position_snapshots (
                    id, account_id, asset_id, reference_date, quantity, avg_price,
                    source_type, run_id, is_manual, created_at, updated_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    str(uuid.uuid4()),
                    "account-logical-001",
                    asset_id,
                    "2026-10-13",
                    100.0,
                    41.33,
                    "MYPROFIT_ATIVOS",
                    str(uuid.uuid4()),
                    0,
                    "2026-10-13 12:00:00",
                    "2026-10-13 12:00:00",
                ),
            )

        err_msg = str(exc_info.value).lower()
        assert "foreign key mismatch" in err_msg
        assert "position_snapshots" in err_msg
        assert "accounts" in err_msg


