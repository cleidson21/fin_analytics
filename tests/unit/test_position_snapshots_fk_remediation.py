def _upgrade_with_foreign_keys(config: Config, revision: str) -> None:
    """Run Alembic with FK enforcement enabled on every migration connection."""
    observed_pragmas: List[int] = []

    def _enable_foreign_keys(dbapi_connection, _connection_record) -> None:
        cursor = dbapi_connection.cursor()
        try:
            cursor.execute("PRAGMA foreign_keys=ON;")
            cursor.execute("PRAGMA foreign_keys;")
            observed_pragmas.append(cursor.fetchone()[0])
        finally:
            cursor.close()

    event.listen(Engine, "connect", _enable_foreign_keys)
    try:
        command.upgrade(config, revision)
    finally:
        event.remove(Engine, "connect", _enable_foreign_keys)
        assert observed_pragmas
        assert set(observed_pragmas) == {1}


